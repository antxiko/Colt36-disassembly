; ----------------------------------------------------------------------
; ############################################################
; LAS DOS RUTINAS DE COPIA
; ############################################################
; Son el motor grafico entero del juego, y caben en 33 bytes.
; Las dos leen sus tres parametros del mismo sitio, 0xD9E1, que
; es donde los deja la subrutina 20 del BASIC. Ninguna de las
; dos devuelve nada ni actualiza esos parametros, y de eso el
; programa saca partido: para el scroll solo reescribe el
; origen, porque el cuanto y el adonde siguen puestos de antes.
; ----------------------------------------------------------------------
usr1:		; DEFUSR1: copia BC bytes de la RAM (HL) a la memoria de video (DE)
	ld hl,(0d9e1h)		;e300
	ld b,h			;e303
	ld c,l			;e304
	ld hl,(0d9e3h)		;e305
	ld d,h			;e308
	ld e,l			;e309
	ld hl,(0d9e5h)		;e30a
	call 0005ch		;e30d   ; BIOS LDIRVM - Block transfers to VRAM from memory | la rutina del sistema que hace la copia a video
	ret			;e310

; ----------------------------------------------------------------------
; DATOS relleno: Dos bytes de relleno entre las dos rutinas, para que la
;   segunda empiece en 0xE313
;   0xe311..0xe313  (2 bytes)
DATA_relleno:
	defb 000h,000h	; e311

; ======================================================================
; CODIGO 0xe313..0xe323  (16 bytes)
; ======================================================================



; ----------------------------------------------------------------------
; ------------------------------------------------------------
; Identica a la de arriba hasta el ultimo momento, donde en vez
; de llamar al sistema hace un LDIR. Se usa una sola vez en todo
; el juego: para llevar el decorado del nivel al area de trabajo.
; Hace falta la copia para que el original quede intacto y se
; pueda repetir el nivel al perder una vida.
; ----------------------------------------------------------------------
usr2:		; DEFUSR2: lo mismo pero de RAM a RAM
	ld hl,(0d9e1h)		;e313   ; el numero de bytes, que la subrutina 20 del BASIC deja en 0xD9E1
	ld b,h			;e316   ; a BC, que es lo que cuenta el LDIR
	ld c,l			;e317
	ld hl,(0d9e3h)		;e318   ; el destino, en 0xD9E3
	ld d,h			;e31b
	ld e,l			;e31c
	ld hl,(0d9e5h)		;e31d   ; y el origen, en 0xD9E5: es el ultimo que se lee, y el unico que el scroll reescribe
	ldir		;e320   ; aqui no hay BIOS que valga: RAM a RAM y en el mismo bloque
	ret			;e322

