; 108        el hueco en blanco, que en los textos del
; programa se escribe con un '0'
; 125 a 155  las letras: numero = codigo ASCII + 60. Ahi
; caen la enye (151), los dos puntos (154) y la
; admiracion (155)
; 156 a 165  las diez cifras, que van por su cuenta
; 166 a 168  la bala y las dos mitades del icono de bandido
; 174 en adelante  los bandidos, en bloques de 2x2
; 255        la casilla vacia, la mas frecuente del decorado
