	ld b,h			;e316
	ld c,l			;e317
	ld hl,(0d9e3h)		;e318
	ld d,h			;e31b
	ld e,l			;e31c
	ld hl,(0d9e5h)		;e31d
	ldir			;e320
	ret			;e322

